def check() -> tuple[int, int]:
    """Run both AES-GCM paths against every known answer. Raises on the
    first mismatch; returns (encrypt cases, FAIL cases) checked."""
    from cryptography.exceptions import InvalidTag
    from cryptography.hazmat.primitives.ciphers.aead import AESGCM

    from . import gcm

    for t in ENCRYPT:
        key, iv, pt, aad, ct, tag = (bytes.fromhex(t[k]) for k in
                                     ("key", "iv", "pt", "aad", "ct", "tag"))
        where = (f"NIST CAVP encrypt PTlen={t['ptlen']} AADlen={t['aadlen']} "
                 f"Count={t['count']}")
        if AESGCM(key).encrypt(iv, pt, aad) != ct + tag:
            raise AssertionError(f"cryptography's AESGCM disagrees with {where}")
        if AESGCM(key).decrypt(iv, ct + tag, aad) != pt:
            raise AssertionError(f"cryptography's AESGCM does not open {where}")
        if gcm.tag(key, iv, aad, ct) != tag:
            raise AssertionError(f"gcm.py's tag disagrees with {where}")
        ks = gcm.keystream(key, iv, -(-len(pt) // 16))
        if bytes(p ^ k for p, k in zip(pt, ks)) != ct:
            raise AssertionError(f"gcm.py's keystream disagrees with {where}")

    for t in DECRYPT_FAIL:
        key, iv, aad, ct, tag = (bytes.fromhex(t[k]) for k in
                                 ("key", "iv", "aad", "ct", "tag"))
        where = (f"NIST CAVP decrypt FAIL PTlen={t['ptlen']} "
                 f"AADlen={t['aadlen']} Count={t['count']}")
        try:
            AESGCM(key).decrypt(iv, ct + tag, aad)
        except InvalidTag:
            pass
        else:
            raise AssertionError(f"cryptography's AESGCM accepted {where}")
        if gcm.tag(key, iv, aad, ct) == tag:
            raise AssertionError(f"gcm.py's tag matches {where}")

    return len(ENCRYPT), len(DECRYPT_FAIL)
